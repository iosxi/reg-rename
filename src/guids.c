/*
 * guids.c - GUID / DEVPROPKEY / PROPERTYKEY の実体を 1 か所で定義する。
 *
 * DEFINE_GUID / DEFINE_DEVPROPKEY / DEFINE_PROPERTYKEY は INITGUID が
 * 定義されているときだけ実体を生成する。二重定義を避けるため、
 * initguid.h を include する翻訳単位はこのファイルだけに限定する。
 */
